#!/usr/bin/env python3
"""
Reorganize gcloud bulk-export Terraform files into a FLAT folder hierarchy that
mirrors GitLab repositories.

Each GitLab repo in fastoss_b/ndl_core declares BQ_DATASET_NAMES in its
.gitlab-ci.yml.  This script reads those declarations from local repo clones
(created by clone_fastoss_b.py) — no network call or GitLab token needed.

It then walks the local tf_export_* directories and copies each .tf file into:

    {output_dir}/{env}/{repo_name}/{prefix}_{file}.tf

where the prefix encodes the resource type:
    ds_{file}.tf               — BigQueryDataset  (e.g. ds_my_dataset.tf)
    t_{file}.tf                — BigQueryTable    (e.g. t_stageai_tablename.tf)
    r_{file}.tf                — BigQueryRoutine  (e.g. r_stageai_routinename.tf)

{file} already carries the dataset prefix (ds_id_table_id) as set by
export_bq_to_tf.py, so no extra ds_name_ prefix is added here.

All resource files for a repo land in the same flat directory, alongside an
auto-generated imports.tf.

Files whose dataset is not claimed by any repo land in:

    {output_dir}/{env}/_unmapped/{prefix}_{file}.tf

Usage (from Cloud Shell):
    # Process all environments
    python organize_tf_export_flat.py

    # Process a single environment
    python organize_tf_export_flat.py --env prod-gke

    # Process several environments
    python organize_tf_export_flat.py --env prod,prod-gke

    # Dry run — print what would be copied without copying
    python organize_tf_export_flat.py --env prod --dry-run

All options:
    --repos-dir  PATH    Directory containing local repo clones with .gitlab-ci.yml files
                         (default: /workspace/repos/fastossb)
    --base-dir   PATH    Parent of tf_export_* dirs (default: /home/nq10083194)
    --output-dir PATH    Destination root (default: {base_dir}/terraform-export-flat)
    --env/--envs LIST    Comma-separated envs to process
                         (default: prod,prod-gke,test,test-gke,dev,dev-gke)
    --dry-run            Print what would be copied without copying
"""

import argparse
import json
import re
import shutil
import sys
from collections import defaultdict
from pathlib import Path

import yaml

_DATASET_ID_RE = re.compile(r'dataset_id\s*=\s*"([^"]+)"')
_IMPORT_CMD_RE = re.compile(r'#\s*terraform import\s+(\S+)\s+(\S+)')

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

GITLAB_CI_FILE = ".gitlab-ci.yml"

ENV_TO_PROJECT = {
    "prod":     "tefde-gcp-fastoss-prod",
    "prod-gke": "tefde-gcp-fastoss-prod-gke",
    "test":     "tefde-gcp-fastoss-test",
    "test-gke": "tefde-gcp-fastoss-test-gke",
    "dev":      "tefde-gcp-fastoss-dev",
    "dev-gke":  "tefde-gcp-fastoss-dev-gke",
}

RESOURCE_TYPES = ["BigQueryDataset", "BigQueryTable", "BigQueryRoutine"]


# ---------------------------------------------------------------------------
# imports.tf generation (Phase 3)
# ---------------------------------------------------------------------------

def generate_imports_file(repo_dir: Path, dry_run: bool) -> None:
    """Write imports.tf to repo_dir.

    Scans all .tf files in the flat repo directory, finds every commented
    `# terraform import TYPE.NAME ID` line, and converts them to native
    `import {}` blocks — without a module prefix, since all resources are in
    the same directory.
    """
    if not repo_dir.exists():
        return

    import_lines = ["# Auto-generated by organize_tf_export_flat.py — do not edit manually.\n"]
    for tf_file in sorted(repo_dir.glob("*.tf")):
        if tf_file.name == "imports.tf":
            continue
        try:
            content = tf_file.read_text(encoding="utf-8")
        except Exception:
            continue
        for m in _IMPORT_CMD_RE.finditer(content):
            resource_addr = m.group(1)  # e.g. google_bigquery_table.my_table
            import_id = m.group(2)      # e.g. projects/.../tables/my_table
            import_lines.append(
                f'\nimport {{\n'
                f'  id = "{import_id}"\n'
                f'  to = {resource_addr}\n'
                f'}}\n'
            )

    imports_content = "".join(import_lines)
    dst = repo_dir / "imports.tf"
    if dry_run:
        print(f"    [DRY-RUN] Would generate {dst}")
    else:
        dst.write_text(imports_content, encoding="utf-8")


# ---------------------------------------------------------------------------
# Phase 1 — build dataset → repo map from local clones
# ---------------------------------------------------------------------------

def build_dataset_repo_map(repos_dir: Path) -> dict[str, str]:
    """Walk repos_dir, find every .gitlab-ci.yml, parse BQ_DATASET_NAMES.

    Returns {dataset_name: repo_name} where repo_name is the folder that
    contains the .gitlab-ci.yml file.
    """
    print(f"\n=== Phase 1: Reading .gitlab-ci.yml files from {repos_dir} ===")
    if not repos_dir.exists():
        print(f"ERROR: repos-dir not found: {repos_dir}")
        sys.exit(1)

    dataset_repo_map: dict[str, str] = {}
    repos_with_datasets = 0

    for ci_path in sorted(repos_dir.rglob(GITLAB_CI_FILE)):
        repo_name = ci_path.parent.name  # folder name = GitLab project name
        try:
            ci = yaml.safe_load(ci_path.read_text(encoding="utf-8")) or {}
        except Exception as exc:
            print(f"  [{repo_name}] WARN: could not parse {ci_path}: {exc}")
            continue

        raw = ci.get("variables", {}).get("BQ_DATASET_NAMES", "")
        if not raw:
            continue

        datasets = [d.strip() for d in str(raw).split(",") if d.strip()]
        repos_with_datasets += 1
        print(f"  [{repo_name}] {len(datasets)} dataset(s): {', '.join(datasets)}")

        for ds in datasets:
            if ds in dataset_repo_map:
                print(f"  WARNING: dataset '{ds}' already claimed by "
                      f"'{dataset_repo_map[ds]}', also claimed by '{repo_name}' — keeping first")
            else:
                dataset_repo_map[ds] = repo_name

    print(f"\n  Total: {repos_with_datasets} repo(s) → {len(dataset_repo_map)} dataset mapping(s)")
    return dataset_repo_map


# ---------------------------------------------------------------------------
# Phase 2 — walk export dirs and copy files
# ---------------------------------------------------------------------------

def _iter_resource_roots(base_dir: Path, env: str, project_id: str, exports_dir: Path | None = None):
    """Yield (resource_type, root_path) for all candidate roots that exist."""
    export_dir = (exports_dir / env) if exports_dir else (base_dir / f"tf_export_{env}")
    if not export_dir.exists():
        print(f"  [SKIP] Export dir not found: {export_dir}")
        return

    # Two path conventions used by gcloud bulk-export:
    candidate_prefixes = [
        export_dir / project_id,
        export_dir / "projects" / project_id,
    ]
    for prefix in candidate_prefixes:
        for rtype in RESOURCE_TYPES:
            candidate = prefix / rtype
            if candidate.exists():
                yield rtype, candidate


def dataset_from_tf(tf_file: Path) -> str:
    """Extract the BQ dataset name from the dataset_id attribute inside a .tf file.

    All gcloud bulk-export resource types (BigQueryTable, BigQueryDataset,
    BigQueryRoutine) include a dataset_id = "..." line in their Terraform output.
    Reading the file is more reliable than inferring the dataset from the path,
    which varies by export layout.
    """
    try:
        content = tf_file.read_text(encoding="utf-8")
        m = _DATASET_ID_RE.search(content)
        if m:
            return m.group(1)
    except Exception:
        pass
    return ""


def collect_tf_files(base_dir: Path, env: str, project_id: str, exports_dir: Path | None = None) -> list[tuple[str, str, Path]]:
    """Return list of (resource_type, dataset_name, absolute_path) for every .tf file."""
    results = []
    seen_roots: set[Path] = set()
    for rtype, root in _iter_resource_roots(base_dir, env, project_id, exports_dir):
        if root in seen_roots:
            continue
        seen_roots.add(root)
        for tf_file in sorted(root.rglob("*.tf")):
            ds = dataset_from_tf(tf_file)
            if ds:
                results.append((rtype, ds, tf_file))
    return results


def inject_deletion_protection(content: str) -> str:
    """Insert deletion_protection = false into google_bigquery_table resources.

    gcloud bulk-export never emits this Terraform-only flag, so we add it
    during reorganisation so that tables can be replaced by Terraform without
    hitting the deletion_protection guard.  The flag is inserted right after
    the opening brace of each resource block.
    """
    if 'resource "google_bigquery_table"' not in content:
        return content
    if "deletion_protection" in content:
        return content  # already present — don't duplicate
    return re.sub(
        r'(resource\s+"google_bigquery_table"\s+"[^"]+"\s*\{)',
        r'\1\n  deletion_protection = false',
        content,
    )


def copy_file(src: Path, dst: Path, dry_run: bool, content: str | None = None) -> bool:
    """Copy src to dst (or write content if provided). Return True if written."""
    if content is not None:
        # Text file with possible injected content — compare by value, not mtime.
        if dst.exists():
            try:
                if dst.read_text(encoding="utf-8") == content:
                    return False  # identical — skip
            except Exception:
                pass
        if dry_run:
            print(f"    [DRY-RUN] {src} → {dst}")
            return True
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(content, encoding="utf-8")
        return True

    # Binary copy (original size+mtime optimisation).
    if dst.exists():
        src_stat = src.stat()
        dst_stat = dst.stat()
        if src_stat.st_size == dst_stat.st_size and abs(src_stat.st_mtime - dst_stat.st_mtime) < 1:
            return False  # identical — skip
    if dry_run:
        print(f"    [DRY-RUN] {src} → {dst}")
        return True
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    return True


def process_env(
    env: str,
    project_id: str,
    base_dir: Path,
    output_dir: Path,
    dataset_repo_map: dict[str, str],
    dry_run: bool,
    exports_dir: Path | None = None,
) -> dict[str, int]:
    """Walk one environment's export and copy files to the flat output tree."""
    tf_files = collect_tf_files(base_dir, env, project_id, exports_dir)
    if not tf_files:
        print(f"  [SKIP] No .tf files found for env={env} project={project_id}")
        return {}

    counts: dict[str, int] = defaultdict(int)
    env_out = output_dir / env
    repos_seen: set[str] = set()

    for rtype, ds_name, src in tf_files:
        repo = dataset_repo_map.get(ds_name, "_unmapped")

        # Build flat filename with resource-type prefix.
        # src.name already carries the dataset prefix (ds_id_table_id.tf) from
        # export_bq_to_tf.py, so we only add the resource-type letter here.
        if rtype == "BigQueryDataset":
            new_name = f"ds_{src.name}"
        elif rtype == "BigQueryTable":
            new_name = f"t_{src.name}"
        else:  # BigQueryRoutine
            new_name = f"r_{src.name}"

        dst = env_out / repo / new_name
        try:
            raw = src.read_text(encoding="utf-8")
            transformed = inject_deletion_protection(raw)
            copied = copy_file(src, dst, dry_run, content=transformed)
        except UnicodeDecodeError:
            copied = copy_file(src, dst, dry_run)
        if copied:
            counts[repo] += 1
        if repo != "_unmapped":
            repos_seen.add(repo)

    # Phase 3: generate imports.tf for every real repo that received files.
    for repo in sorted(repos_seen):
        generate_imports_file(env_out / repo, dry_run)

    return counts


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--mapping-file",
        default=None,
        metavar="PATH",
        help="JSON file {dataset_name: repo_name} from the devops-reports-dataset-mapping "
             "Cloud Run job. When provided, --repos-dir is ignored.",
    )
    parser.add_argument(
        "--repos-dir", default="/workspace/repos/fastossb",
        help="Directory containing local repo clones (default: /workspace/repos/fastossb). "
             "Ignored when --mapping-file is provided.",
    )
    parser.add_argument(
        "--base-dir", default="/home/nq10083194",
        help="Parent of tf_export_* dirs (default: /home/nq10083194). "
             "Ignored when --exports-dir is provided.",
    )
    parser.add_argument(
        "--exports-dir", default=None,
        help="Parent directory whose subfolders are named after environments "
             "(e.g. /home/nq10083194/gcp-exports, containing prod/, test/, dev/, …). "
             "When provided, --base-dir is ignored for locating export files.",
    )
    parser.add_argument(
        "--output-dir", default=None,
        help="Output root (default: {base-dir}/terraform-export-flat)",
    )
    env_group = parser.add_mutually_exclusive_group()
    env_group.add_argument(
        "--env", dest="envs", default=None, metavar="ENV[,ENV...]",
        help="Comma-separated env(s) to process, e.g. prod-gke or prod,prod-gke "
             "(default: all six)",
    )
    env_group.add_argument(
        "--envs", dest="envs", default=None, metavar="ENV[,ENV...]",
        help="Alias for --env",
    )
    parser.add_argument("--dry-run", action="store_true",
                        help="Print planned copies without writing files")
    args = parser.parse_args()

    base_dir = Path(args.base_dir)
    repos_dir = Path(args.repos_dir)
    exports_dir = Path(args.exports_dir) if args.exports_dir else None
    output_dir = Path(args.output_dir) if args.output_dir else base_dir / "terraform-export-flat"
    envs_raw = args.envs if args.envs else ",".join(ENV_TO_PROJECT)
    envs = [e.strip() for e in envs_raw.split(",") if e.strip()]

    unknown_envs = [e for e in envs if e not in ENV_TO_PROJECT]
    if unknown_envs:
        print(f"ERROR: unknown env(s): {unknown_envs}. Valid: {list(ENV_TO_PROJECT)}")
        sys.exit(1)

    # Phase 1: build dataset → repo mapping
    if args.mapping_file:
        with open(args.mapping_file, encoding="utf-8") as f:
            dataset_repo_map = json.load(f)
        print(f"\n=== Phase 1: Loaded {len(dataset_repo_map)} dataset mapping(s) "
              f"from {args.mapping_file} ===")
    else:
        dataset_repo_map = build_dataset_repo_map(repos_dir)

    # Phase 2: walk each env and copy files
    print(f"\n=== Phase 2: Copying Terraform files ({'DRY-RUN' if args.dry_run else 'LIVE'}) ===")
    print(f"  Environments : {', '.join(envs)}")
    print(f"  Output dir   : {output_dir}\n")

    grand_total = 0
    for env in envs:
        project_id = ENV_TO_PROJECT[env]
        print(f"[{env}] → {project_id}")
        counts = process_env(env, project_id, base_dir, output_dir, dataset_repo_map, args.dry_run, exports_dir)
        env_total = sum(counts.values())
        grand_total += env_total
        unmapped = counts.pop("_unmapped", 0)
        for repo, n in sorted(counts.items()):
            print(f"  {repo}: {n} file(s)")
        if unmapped:
            print(f"  _unmapped: {unmapped} file(s)  ← no GitLab repo claims these datasets")
        print(f"  Subtotal: {env_total} file(s)\n")

    print(f"{'[DRY-RUN] ' if args.dry_run else ''}Done. {grand_total} file(s) total.")


if __name__ == "__main__":
    main()
